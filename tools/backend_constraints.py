"""Write backend/constraints.txt: the exact versions of every backend dependency in a tested environment.

run.sh, run.bat, the Dockerfile and CI install with `pip install -c constraints.txt -e .`, so a first run
gets the versions the test suite passed with, while backend/pyproject.toml keeps its version ranges.

To refresh (after changing dependencies, or to pick up newer releases):
    cd backend
    python -m venv /tmp/pd-fresh && /tmp/pd-fresh/bin/pip install -e ".[dev]"   # latest within the ranges
    /tmp/pd-fresh/bin/python -m pytest -q                                       # must pass
    /tmp/pd-fresh/bin/python ../tools/backend_constraints.py                    # rewrites constraints.txt
Then let CI run on Linux, Windows and macOS (Python 3.11 and 3.13) before merging.

Packages that the tested machine did not need (for example colorama, which click uses on Windows only)
are not listed and install at their newest compatible version.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from third_party_notices import ROOT, norm, python_packages  # noqa: E402


def main() -> int:
    dists = {norm(d.metadata["Name"]): d for d in python_packages(("runtime", "dev"))}
    lines = ["# Exact versions the backend was tested with. Generated by tools/backend_constraints.py; see that",
             "# file for how to refresh it. pyproject.toml keeps the version ranges; this file pins one tested set.",
             f"# Generated with Python {sys.version.split()[0]} on {sys.platform}."]
    lines += [f"{d.metadata['Name']}=={d.version}" for _, d in sorted(dists.items())]
    (ROOT / "backend" / "constraints.txt").write_text("\n".join(lines) + "\n")
    print(f"Wrote backend/constraints.txt with {len(dists)} packages.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
